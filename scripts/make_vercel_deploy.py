"""Generate the small "bootstrap" file sets used to deploy WasteWise to Vercel by file upload.

Why: the Vercel projects are not linked to GitHub (linking needs a GitHub Login Connection on the
Vercel account), and Vercel's anonymous GitHub fetches are rate-limited. Instead we upload a few
tiny files that pull an exact, pinned version of the code:

* web (Next.js)   - the install step downloads the frontend sources of commit <sha> from
                    codeload.github.com and then runs `npm ci` + `next build` as usual.
* api (FastAPI)   - the serverless entry point downloads a release bundle (backend code + model
                    artifacts, produced by `git archive`), verifies its SHA-256, extracts it to /tmp
                    and imports `app.main:app`. Nothing unverified is ever executed.

Usage:
    python scripts/make_vercel_deploy.py web --sha <commit>
    python scripts/make_vercel_deploy.py api --bundle-url <url> --bundle-sha256 <hex>

Output goes to deploy/vercel/<target>/ (committed, so every deployment is reviewable).
Once GitHub is connected to Vercel, normal Git deployments (root directories frontend/ and backend/)
make this unnecessary.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "deploy" / "vercel"
REPO = "Madhurchaudhary/Wastewise"
REGION = "bom1"  # Mumbai: closest to users and to Supabase ap-south-1


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print("wrote", path.relative_to(ROOT))


def make_web(sha: str) -> None:
    if not re.fullmatch(r"[0-9a-f]{40}", sha):
        raise SystemExit("--sha must be a full 40-character commit hash")
    d = OUT / "web"
    # package.json is uploaded so Vercel detects Next.js and its version before install.
    write(d / "package.json", (ROOT / "frontend/package.json").read_text())
    write(d / "fetch_source.sh", f"""#!/usr/bin/env bash
# Downloads the WasteWise frontend sources of a pinned commit (generated by scripts/make_vercel_deploy.py).
set -euo pipefail
SHA="{sha}"
curl -fsSL --retry 3 "https://codeload.github.com/{REPO}/tar.gz/$SHA" \\
  | tar -xz --strip-components=2 "Wastewise-$SHA/frontend"
echo "WasteWise frontend sources: commit $SHA"
""")
    write(d / "vercel.json", json.dumps({
        "$schema": "https://openapi.vercel.sh/vercel.json",
        "framework": "nextjs",
        "installCommand": "bash fetch_source.sh && npm ci",
        "buildCommand": "npm run build",
        "regions": [REGION],
    }, indent=2) + "\n")


def make_api(bundle_url: str, bundle_sha256: str) -> None:
    if not re.fullmatch(r"[0-9a-f]{64}", bundle_sha256):
        raise SystemExit("--bundle-sha256 must be a 64-character hex digest")
    if not bundle_url.startswith("https://github.com/"):
        raise SystemExit("--bundle-url must be a GitHub release asset URL")
    d = OUT / "api"
    reqs = [ln for ln in (ROOT / "backend/requirements.txt").read_text().splitlines()
            if not ln.startswith("uvicorn")]   # the ASGI server is provided by Vercel
    write(d / "requirements.txt", "\n".join(reqs) + "\n")
    write(d / ".python-version", (ROOT / "backend/.python-version").read_text())
    write(d / "vercel.json", json.dumps({
        "$schema": "https://openapi.vercel.sh/vercel.json",
        "regions": [REGION],
        "functions": {"api/index.py": {"maxDuration": 60, "memory": 2048}},
        "rewrites": [{"source": "/(.*)", "destination": "/api/index"}],
    }, indent=2) + "\n")
    write(d / "api/index.py", f'''"""Vercel entry point (file-upload deployment, generated by scripts/make_vercel_deploy.py).

Downloads the pinned WasteWise API bundle (backend code + model artifacts, made with `git archive`),
verifies its SHA-256, extracts it to /tmp once per instance and exposes the FastAPI app.
The model files inside are verified again against model_card.json when they are loaded.
"""
import hashlib
import os
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

BUNDLE_URL = "{bundle_url}"
BUNDLE_SHA256 = "{bundle_sha256}"

target = Path(tempfile.gettempdir()) / f"wastewise-{{BUNDLE_SHA256[:16]}}"
if not (target / ".ready").exists():
    tmp = target.with_suffix(".tar.gz")
    target.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(BUNDLE_URL, timeout=60) as r, open(tmp, "wb") as f:
        h = hashlib.sha256()
        for chunk in iter(lambda: r.read(1 << 20), b""):
            h.update(chunk)
            f.write(chunk)
    if h.hexdigest() != BUNDLE_SHA256:
        tmp.unlink(missing_ok=True)
        raise RuntimeError("WasteWise API bundle checksum mismatch - refusing to start")
    with tarfile.open(tmp) as tar:
        tar.extractall(target, filter="data")
    tmp.unlink(missing_ok=True)
    (target / ".ready").write_text(BUNDLE_SHA256)

os.environ.setdefault("MODEL_DIR", str(target / "backend" / "model_artifacts"))
sys.path.insert(0, str(target / "backend"))

from app.main import app  # noqa: E402,F401
''')


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="target", required=True)
    w = sub.add_parser("web")
    w.add_argument("--sha", required=True)
    a = sub.add_parser("api")
    a.add_argument("--bundle-url", required=True)
    a.add_argument("--bundle-sha256", required=True)
    args = ap.parse_args()
    if args.target == "web":
        make_web(args.sha)
    else:
        make_api(args.bundle_url, args.bundle_sha256)


if __name__ == "__main__":
    main()
