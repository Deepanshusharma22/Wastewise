"""Generate the small "bootstrap" file sets used to deploy WasteWise to Vercel by file upload.

Why: the Vercel projects are not linked to GitHub (linking needs a GitHub Login Connection on the
Vercel account), and Vercel's anonymous GitHub fetches are rate-limited. Instead we upload a few
tiny files that pull an exact, pinned version of the code:

* web (Next.js)   - the install step downloads the frontend sources of commit <sha> from
                    codeload.github.com and then runs `npm ci` + `next build` as usual.
* api (FastAPI)   - the serverless entry point downloads a release bundle (backend code + model
                    artifacts, produced by `git archive`), verifies its SHA-256, extracts it to /tmp
                    and imports `app.main:app`. Nothing unverified is ever executed.

Usage:
    python scripts/make_vercel_deploy.py web --sha <commit>
    python scripts/make_vercel_deploy.py api --bundle-url <url> --bundle-sha256 <hex>

Output goes to deploy/vercel/<target>/ (committed, so every deployment is reviewable).
Once GitHub is connected to Vercel, normal Git deployments (root directories frontend/ and backend/)
make this unnecessary.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "deploy" / "vercel"
REPO = "Madhurchaudhary/Wastewise"
REGION = "bom1"  # Mumbai: closest to users and to Supabase ap-south-1


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print("wrote", path)


def make_web(sha: str) -> None:
    if not re.fullmatch(r"[0-9a-f]{40}", sha):
        raise SystemExit("--sha must be a full 40-character commit hash")
    d = OUT / "web"
    # package.json is uploaded so Vercel detects Next.js and its version before install.
    write(d / "package.json", (ROOT / "frontend/package.json").read_text())
    write(d / "fetch_source.sh", f"""#!/usr/bin/env bash
# Downloads the WasteWise frontend sources of a pinned commit (generated by scripts/make_vercel_deploy.py).
set -euo pipefail
SHA="{sha}"
curl -fsSL --retry 3 "https://codeload.github.com/{REPO}/tar.gz/$SHA" \\
  | tar -xz --strip-components=2 "Wastewise-$SHA/frontend"
echo "WasteWise frontend sources: commit $SHA"
""")
    write(d / "vercel.json", json.dumps({
        "$schema": "https://openapi.vercel.sh/vercel.json",
        "framework": "nextjs",
        "installCommand": "bash fetch_source.sh && npm ci",
        "buildCommand": "npm run build",
        "regions": [REGION],
    }, indent=2) + "\n")


def make_api(bundle_url: str, bundle_sha256: str) -> None:
    if not re.fullmatch(r"[0-9a-f]{64}", bundle_sha256):
        raise SystemExit("--bundle-sha256 must be a 64-character hex digest")
    if not bundle_url.startswith("https://github.com/"):
        raise SystemExit("--bundle-url must be a github.com URL (release asset or /archive/<sha>.tar.gz)")
    d = OUT / "api"
    reqs = [ln for ln in (ROOT / "backend/requirements.txt").read_text().splitlines()
            if not ln.startswith("uvicorn")]   # the ASGI server is provided by Vercel
    write(d / "requirements.txt", "\n".join(reqs) + "\n")
    write(d / ".python-version", (ROOT / "backend/.python-version").read_text())
    write(d / "vercel.json", json.dumps({
        "$schema": "https://openapi.vercel.sh/vercel.json",
        "framework": "fastapi",
        "regions": [REGION],
        # `fastapi` framework preset: Vercel detects the root-level `index.py` entry point and routes
        # every path to the ASGI app. No catch-all rewrite (backend-framework rewrites pass the
        # rewritten path to the app, so every route would 404) and no api/ legacy function.
    }, indent=2) + "\n")
    write(d / "index.py", f'''"""Vercel entry point (file-upload deployment, generated by scripts/make_vercel_deploy.py).

On the first request it downloads the pinned WasteWise API bundle (backend code + model artifacts:
a GitHub commit archive or a `git archive HEAD backend` release asset), verifies its SHA-256,
extracts only backend/ to /tmp (once per instance) and hands every request to `app.main:app`.
The model files inside are verified again against model_card.json when they are loaded.

The bootstrap is lazy (not at import time) so a slow download can never hit the function's init
limit, and GET /__bootstrap reports its state (no secrets) for diagnosing cold starts.
"""
import asyncio
import hashlib
import json
import os
import sys
import tarfile
import tempfile
import threading
import time
import urllib.request
from pathlib import Path

BUNDLE_URL = "{bundle_url}"
BUNDLE_SHA256 = "{bundle_sha256}"
TARGET = Path(tempfile.gettempdir()) / f"wastewise-{{BUNDLE_SHA256[:16]}}"

_lock = threading.Lock()
_state = {{"status": "cold", "error": None, "seconds": None, "bundle_sha256": BUNDLE_SHA256}}
_inner = None


def _extract() -> None:
    tmp = TARGET.with_suffix(".tar.gz")
    TARGET.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(BUNDLE_URL, timeout=60) as r, open(tmp, "wb") as f:
        h = hashlib.sha256()
        for chunk in iter(lambda: r.read(1 << 20), b""):
            h.update(chunk)
            f.write(chunk)
    if h.hexdigest() != BUNDLE_SHA256:
        tmp.unlink(missing_ok=True)
        raise RuntimeError("WasteWise API bundle checksum mismatch - refusing to start")
    with tarfile.open(tmp) as tar:
        # Accept both `git archive HEAD backend` (members start with backend/) and GitHub commit
        # archives (members start with <repo>-<sha>/). Only backend/ is extracted.
        members = []
        for m in tar.getmembers():
            parts = Path(m.name).parts
            if parts and parts[0] != "backend":
                parts = parts[1:]
            if not parts or parts[0] != "backend":
                continue
            if m.name.startswith("/") or ".." in parts or not (m.isfile() or m.isdir()):
                raise RuntimeError(f"unsafe path in WasteWise API bundle: {{m.name}}")
            m.name = str(Path(*parts))
            members.append(m)
        if not members:
            raise RuntimeError("WasteWise API bundle contains no backend/ directory")
        try:
            tar.extractall(TARGET, members=members, filter="data")
        except TypeError:  # Python without extraction filters; members were checked above
            tar.extractall(TARGET, members=members)
    tmp.unlink(missing_ok=True)
    (TARGET / ".ready").write_text(BUNDLE_SHA256)


def _bootstrap():
    global _inner
    with _lock:
        if _inner is not None:
            return _inner
        t0 = time.perf_counter()
        _state["status"] = "bootstrapping"
        try:
            if not (TARGET / ".ready").exists():
                _extract()
            os.environ.setdefault("MODEL_DIR", str(TARGET / "backend" / "model_artifacts"))
            if str(TARGET / "backend") not in sys.path:
                sys.path.insert(0, str(TARGET / "backend"))
            from app.main import app as inner
            _inner = inner
            _state.update(status="ready", error=None)
        except Exception as exc:  # reported via /__bootstrap; retried on the next request
            _state.update(status="failed", error=f"{{type(exc).__name__}}: {{exc}}"[:500])
            raise
        finally:
            _state["seconds"] = round(time.perf_counter() - t0, 2)
        return _inner


async def _send_json(send, status: int, body: dict) -> None:
    data = json.dumps(body).encode()
    await send({{"type": "http.response.start", "status": status,
                "headers": [(b"content-type", b"application/json"), (b"cache-control", b"no-store")]}})
    await send({{"type": "http.response.body", "body": data}})


async def app(scope, receive, send):
    if scope["type"] == "lifespan":  # the inner app initialises lazily (serverless-safe)
        while True:
            msg = await receive()
            if msg["type"] == "lifespan.startup":
                await send({{"type": "lifespan.startup.complete"}})
            elif msg["type"] == "lifespan.shutdown":
                await send({{"type": "lifespan.shutdown.complete"}})
                return
    if scope["type"] == "http" and scope.get("path") == "/__bootstrap":
        if _inner is None:
            try:
                await asyncio.to_thread(_bootstrap)
            except Exception:
                pass
        await _send_json(send, 200, _state)
        return
    try:
        inner = _inner or await asyncio.to_thread(_bootstrap)
    except Exception:
        if scope["type"] == "http":
            await _send_json(send, 503, {{"error": {{"code": "bootstrap_failed",
                                                   "message": "The API is starting or failed to start.",
                                                   "request_id": None}}}})
        return
    await inner(scope, receive, send)
''')


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="target", required=True)
    w = sub.add_parser("web")
    w.add_argument("--sha", required=True)
    a = sub.add_parser("api")
    a.add_argument("--bundle-url", required=True)
    a.add_argument("--bundle-sha256", required=True)
    args = ap.parse_args()
    if args.target == "web":
        make_web(args.sha)
    else:
        make_api(args.bundle_url, args.bundle_sha256)


if __name__ == "__main__":
    main()
